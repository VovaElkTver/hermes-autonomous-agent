"""Д7 integration: service forms must not train the peer bot (form-storm).

Incident 28.11, room #hermes-win (also visible as 'All Hermes bots'): two gateways of this
fork answered each other's status forms — ``⏸``/``⏳ Queued``/``🧠 recalled``/
``↪ Redirected current run``/``⚠️ silence marker`` — 30+ forms per minute; the model-level
NO_REPLY cannot stop it because the noise is generated by the receiving/queueing layer.

ТЗ v2 requirements:
  (а) service forms addressed-only AND msgtype=m.notice;
  (б) unaddressed bot messages never enter the queue;
  (в) bot-vs-bot silence marker is a normal outcome, not a ⚠️ notice or re-opened turn.

Receiving convention already exists: peer ``m.notice`` is dropped unless
``process_notices`` opt-in (adapter line ~2004). The storm lives because the SEND side
emits service text as ``m.text``.
"""

import inspect
import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))


def _adapter_module_source():
    from plugins.platforms.matrix import adapter
    return inspect.getsource(adapter)


def test_notice_drop_convention_is_default():
    """Green pin: peer m.notice is ignored by default (process_notices opt-in, default false)."""
    src = _adapter_module_source()
    assert '"process_notices", "MATRIX_PROCESS_NOTICES", "false"' in src
    assert 'if msgtype == "m.notice" and not self._process_notices' in src


@pytest.mark.xfail(strict=True, reason="Д7(а): service/status senders still emit m.text, so the "
                                       "peer bot admits them as human input (storm 28.11)")
def test_service_form_senders_use_notice_msgtype():
    """Every machinery-form sender must choose m.notice; today the adapter has no notice-typed
    send path for status/queue/response forms."""
    src = _adapter_module_source()
    assert 'send_notice' in src or '"msgtype": "m.notice"' in src or 'msgtype="m.notice"' in src


@pytest.mark.xfail(strict=True, reason="Д7(б): queue admission does not filter unaddressed peer-bot "
                                       "messages; in the incident room their forms were captured as input")
def test_unaddressed_bot_messages_stay_out_of_the_queue():
    """The admission path (gateway/session_ingress.py — the one owner of messaging admission)
    must apply an addressed filter (mention/reply) for peer-bot senders, independent of the
    operator ``allow_room_mentions`` opt-in."""
    from gateway import session_ingress
    src = inspect.getsource(session_ingress.admit_message)
    assert "bot" in src and ("mention" in src or "reply" in src or "addressed" in src), \
        "admit_message has no bot-address filter"


@pytest.mark.xfail(strict=True, reason="Д7(в): a bare silence marker on a bot-vs-bot turn surfaces "
                                       "as a visible ⚠️/re-opened handling instead of vanishing")
def test_bot_vs_bot_silence_marker_is_ordinary():
    """response_filters decides whether a successful silence marker may stay silent; it must be
    True for machinery (bot-vs-bot) turns without the human-visible fallback."""
    from gateway import response_filters
    src = inspect.getsource(response_filters)
    assert "bot" in src, "response_filters has no bot-vs-bot silence clause"
